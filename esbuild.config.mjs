import { builtinModules } from "node:module";
import process from "node:process";
import esbuild from "esbuild";

const production = process.argv[2] === "production";
const options = {
	banner: {
		js: `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD.
Source: https://github.com/Fred-Ko/obsidian-jekyll-exporter
*/`,
	},
	entryPoints: ["src/main.ts"],
	bundle: true,
	external: [
		"obsidian",
		"electron",
		"@codemirror/autocomplete",
		"@codemirror/collab",
		"@codemirror/commands",
		"@codemirror/language",
		"@codemirror/lint",
		"@codemirror/search",
		"@codemirror/state",
		"@codemirror/view",
		"@lezer/common",
		"@lezer/highlight",
		"@lezer/lr",
		...builtinModules,
		...builtinModules.map((module) => `node:${module}`),
	],
	format: "cjs",
	target: "es2022",
	logLevel: "info",
	sourcemap: production ? false : "inline",
	treeShaking: true,
	outfile: "main.js",
	minify: production,
};

if (production) {
	await esbuild.build(options);
} else {
	const context = await esbuild.context(options);
	await context.watch();
}
